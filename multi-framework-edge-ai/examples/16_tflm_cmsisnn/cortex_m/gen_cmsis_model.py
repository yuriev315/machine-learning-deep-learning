#!/usr/bin/env python3
"""Turn the real INT8 TFLite model into C: weights, biases and per-channel requantization parameters for CMSIS-NN.
This is the deployment artifact for a microcontroller: plain const arrays, no interpreter and no flatbuffer."""
import math, os, sys
import numpy as np
from ai_edge_litert.interpreter import Interpreter, OpResolverType
R = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
tfl = os.path.join(R, "examples/artifacts/tensorflow/tinycnn_int8.tflite"); out = sys.argv[1]
i = Interpreter(tfl, experimental_op_resolver_type=OpResolverType.BUILTIN_WITHOUT_DEFAULT_DELEGATES); i.allocate_tensors()
T = {t["index"]: t for t in i.get_tensor_details()}
ops = [o for o in i._get_ops_details() if o["op_name"] != "DELEGATE"]
assert [o["op_name"] for o in ops] == ["CONV_2D", "MAX_POOL_2D", "CONV_2D", "MAX_POOL_2D", "RESHAPE", "FULLY_CONNECTED"], [o["op_name"] for o in ops]
def qm(x):
    """Same decomposition TFLite uses: x = m * 2^(e-31)"""
    m, e = math.frexp(x); q = int(round(m * (1 << 31)))
    if q == 1 << 31: q //= 2; e += 1
    return q, e
def q(idx): return T[idx]["quantization_parameters"]
def arr(name, a, ct):
    return f"static const {ct} {name}[{a.size}] = {{{','.join(str(int(v)) for v in a.flatten())}}};\n"
s = "/* Generated by gen_cmsis_model.py from tinycnn_int8.tflite. Do not edit. */\n#include <stdint.h>\n"
def layer(name, op):
    global s
    x, w, b, y = op["inputs"][0], op["inputs"][1], op["inputs"][2], op["outputs"][0]
    si, so = float(q(x)["scales"][0]), float(q(y)["scales"][0]); ws = q(w)["scales"]  # plain doubles: TFLite computes these in double, and numpy float32 would lose precision
    M = [qm(si * float(v) / so) for v in ws]
    s += arr(f"{name}_w", i.get_tensor(w), "int8_t") + arr(f"{name}_b", i.get_tensor(b), "int32_t")
    s += arr(f"{name}_m", np.array([m for m, _ in M]), "int32_t") + arr(f"{name}_s", np.array([e for _, e in M]), "int32_t")
    s += f"#define {name.upper()}_IN_ZP ({int(q(x)['zero_points'][0])})\n#define {name.upper()}_OUT_ZP ({int(q(y)['zero_points'][0])})\n"
layer("c1", ops[0]); layer("c2", ops[2]); layer("fc", ops[5])
d = np.load(os.path.join(R, "examples/data/digits.npz")); xt, yt = d["x_test"], d["y_test"]
qi = q(ops[0]["inputs"][0]); si, zi = float(qi["scales"][0]), int(qi["zero_points"][0])
i8 = np.clip(np.rint(xt / si) + zi, -128, 127).astype(int)   # same quantization as the C API runner
s += f"#define N_TEST {len(xt)}\n" + arr("test_x", i8, "int8_t") + arr("test_y", yt, "uint8_t")
open(out, "w").write(s)
# Reference: predictions of the desktop LiteRT interpreter on the same inputs, kept to compare with the MCU result.
ii = i.get_input_details()[0]; oi = i.get_output_details()[0]; p = []
for u in i8:
    i.set_tensor(ii["index"], u.astype(np.int8).reshape(1, 8, 8, 1)); i.invoke(); p.append(int(i.get_tensor(oi["index"]).argmax()))
print("litert_reference_accuracy", float(np.mean(np.array(p) == yt)), "preds_hash", sum((k + 1) * v for k, v in enumerate(p)))
